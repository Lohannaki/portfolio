// Active lang — default FR, persisted across sessions
window.LANG = localStorage.getItem("portfolio-lang") || "fr";

window.setLang = function(lang) {
  window.LANG = lang;
  localStorage.setItem("portfolio-lang", lang);
  (window._langListeners || []).forEach(fn => fn(lang));
};

window._langListeners = [];
window.onLangChange = function(fn) {
  window._langListeners.push(fn);
  return () => { window._langListeners = window._langListeners.filter(f => f !== fn); };
};

// t("hero.desc") shortcut
window.t = function(path) {
  return path.split(".").reduce((o, k) => o && o[k], window.I18N[window.LANG]);
};
